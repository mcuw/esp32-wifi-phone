#!/usr/bin/env python3
"""Embed the built setup page (web/dist) into the app as a C source file.

    pack_web.py <web/dist> <out.c>

Each file becomes a byte array, gzip-compressed when that makes it smaller,
plus a table web_files[] that provision.c serves from. With the page inside
the app image, an OTA update brings the matching page along (issue #16).
A missing dist directory gives an empty table (and a CMake warning).
"""
import gzip
import pathlib
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript", ".mjs": "text/javascript",
    ".css": "text/css",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
    ".txt": "text/plain",
}


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append(",".join(str(b) for b in data[i:i + 24]))
    return ",\n".join(rows)


def main():
    dist, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    files = sorted(p for p in dist.rglob("*") if p.is_file()) if dist.is_dir() else []
    arrays, rows, raw_total, packed_total = [], [], 0, 0
    for i, p in enumerate(files):
        raw = p.read_bytes()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        use_gz = len(gz) + 64 < len(raw)
        data = gz if use_gz else raw
        raw_total += len(raw)
        packed_total += len(data)
        uri = "/" + p.relative_to(dist).as_posix()
        if any(c in uri for c in '"\\') or len(uri) > 120:
            sys.exit(f"pack_web: unsupported file name {uri!r}")
        mime = MIME.get(p.suffix.lower(), "application/octet-stream")
        arrays.append(f"static const uint8_t f{i}[] = {{\n{c_bytes(data) or '0'}\n}};")
        rows.append(f'    {{ "{uri}", "{mime}", f{i}, {len(data)}, {"true" if use_gz else "false"} }},')

    out.write_text(
        "/* Generated by tools/pack_web.py from web/dist - do not edit. */\n"
        '#include "web_files.h"\n\n'
        + "\n".join(arrays) + "\n\n"
        + "const web_file_t web_files[] = {\n" + "\n".join(rows)
        + ("\n" if rows else "") + "    { 0 }\n};\n"
        + f"const size_t web_files_count = {len(rows)};\n")
    print(f"pack_web: {len(rows)} files, {raw_total} -> {packed_total} bytes")


if __name__ == "__main__":
    main()
